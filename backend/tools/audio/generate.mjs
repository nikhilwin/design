#!/usr/bin/env node
// Renders the audio library: music loops and sound effects, written as Opus in Ogg under backend/data/audio/ together
// with the manifest backend/data/audio_library.json (checksums, durations, waveform peaks, licence).
//
//   node generate.mjs                       everything (about five minutes; run it with `nice`)
//   node generate.mjs --only sunrise-run,pop-small   just these ids (the rest of the manifest is kept)
//   node generate.mjs --out DIR --manifest FILE      write somewhere else
//
// The renders are deterministic: the same code and the same ffmpeg give the same bytes. Every sound is an original
// work generated by code in this directory, released under CC0-1.0.

import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { peaks } from './analysis.mjs'
import { EFFECTS } from './effects.mjs'
import { MUSIC } from './catalog.mjs'
import { compose } from './moods.mjs'
import { SR, biquadFilter, clamp, dbToGain, fadeEdges, limit, stereo } from './dsp.mjs'
import { activeLoudness, integratedLoudness, rms, samplePeak, toDb, truePeak } from './loudness.mjs'
import { decode, encodeOpus, sha256, writeJson } from './media.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const option = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback)
const outDir = resolve(option('--out', join(here, '..', '..', 'data', 'audio')))
const manifestPath = resolve(option('--manifest', join(here, '..', '..', 'data', 'audio_library.json')))
const only = option('--only', '') ? new Set(option('--only', '').split(',')) : null

export const RELEASE = '2026.10.1'
const LICENSE = { spdx: 'CC0-1.0', url: 'https://creativecommons.org/publicdomain/zero/1.0/', holder: 'Doory contributors', note: 'Original works generated by backend/tools/audio; dedicated to the public domain.' }
const MUSIC_TARGET_LUFS = -16
const SFX_TARGET_LUFS = -17
const SFX_PEAK_CEILING_DB = -1.5

function previous() {
  if (!existsSync(manifestPath)) return new Map()
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  return new Map(manifest.tracks.map((t) => [t.id, t]))
}

/** Level, fades and DC for a sound effect; trims trailing silence, adds a few milliseconds of silence in front. */
function finishEffect(raw, extraGainDb = 0) {
  const left = raw.l ?? raw
  const right = raw.r ?? raw
  let end = left.length
  const floor = 10 ** (-66 / 20)
  while (end > 1 && Math.abs(left[end - 1]) < floor && Math.abs(right[end - 1]) < floor) end--
  const body = Math.min(left.length, end + Math.round(0.01 * SR))
  const lead = Math.round(0.004 * SR)
  // A full codec frame of silence at each end: the codec's smear (pre-echo and ringing) lands in silence, so the
  // decoded file starts and ends at zero.
  const tail = Math.round(0.03 * SR)
  const buf = stereo(lead + body + tail)
  buf.l.set(biquadFilter(left.subarray(0, body), 'highpass', 22, 0.7071), lead)
  if (raw.r) buf.r.set(biquadFilter(right.subarray(0, body), 'highpass', 22, 0.7071), lead)
  fadeEdges(buf.l.subarray(lead, lead + body), Math.round(0.002 * SR), Math.round(0.015 * SR))
  if (raw.r) fadeEdges(buf.r.subarray(lead, lead + body), Math.round(0.002 * SR), Math.round(0.015 * SR))
  else buf.r.set(buf.l)
  const channels = [buf.l, buf.r]
  const gain = dbToGain(SFX_TARGET_LUFS - activeLoudness(channels) + extraGainDb)
  for (let i = 0; i < buf.length; i++) {
    buf.l[i] *= gain
    buf.r[i] *= gain
  }
  limit(buf, { ceilingDb: SFX_PEAK_CEILING_DB, lookaheadMs: 1, releaseMs: 40 })
  const mono = !raw.r || buf.l.every((v, i) => Math.abs(v - buf.r[i]) < 1e-6)
  return { l: buf.l, r: buf.r, mono }
}

function describe(channels) {
  return { lufs: integratedLoudness(channels), peakDb: toDb(samplePeak(channels)), truePeakDb: toDb(truePeak(channels)) }
}

const round = (value, digits = 1) => Number(value.toFixed(digits))

/**
 * Encodes and decodes again, and refuses a result that does not sound like its source: libopus can misbehave on some
 * very tonal signals at some bitrates (the decoded level swells to several times the original), so the encode is
 * verified and retried at the next bitrate. Returns the file bytes and the decoded channels.
 */
function encodeVerified(channels, path, kbpsOptions, meta) {
  const sourcePeak = samplePeak(channels)
  const sourceRms = rms(channels)
  for (const kbps of kbpsOptions) {
    const bytes = encodeOpus(channels, path, { kbps, ...meta })
    const decoded = decode(path, channels.length)
    const peakOk = samplePeak(decoded) <= sourcePeak * 1.5 + 0.01
    const levelOk = Math.abs(toDb(rms(decoded)) - toDb(sourceRms)) <= 2.5
    if (peakOk && levelOk) return { bytes, decoded, kbps }
  }
  throw new Error(`${path}: no bitrate in ${kbpsOptions.join(', ')} kbit/s reproduces the signal`)
}

function renderMusic(spec) {
  const { song, mix } = compose(spec)
  const path = join(outDir, 'music', `${spec.id}.ogg`)
  // The codec overshoots the limiter's ceiling by up to a couple of decibels: lower the ceiling until the file's true
  // peak stays under -1 dBTP (most tracks pass at the first try).
  for (const ceilingDb of [-1.2, -2.2, -3.2]) {
    const result = song.render({ ...mix, target: MUSIC_TARGET_LUFS, ceilingDb })
    const { bytes, decoded } = encodeVerified([result.audio.l, result.audio.r], path, [48, 64, 96], { title: spec.title, album: 'Doory audio library' })
    const measured = describe(decoded)
    if (measured.truePeakDb > -1 && ceilingDb > -3.2) continue
    return {
      entry: {
        id: spec.id,
        kind: 'music',
        title: spec.title,
        mood: spec.mood,
        genre: spec.genre,
        tags: spec.tags,
        bpm: spec.bpm,
        key: `${spec.key} ${spec.scale}`,
        loop: true,
        channels: 2,
        durationMs: Math.round((decoded[0].length / SR) * 1000),
        lufs: round(measured.lufs),
        peakDb: round(measured.peakDb),
        file: `music/${spec.id}.ogg`,
        bytes: bytes.length,
        sha256: sha256(bytes),
        peaks: peaks(decoded),
      },
    }
  }
  throw new Error(`${spec.id}: no ceiling keeps the true peak under -1 dBTP`)
}

function renderEffect(effect) {
  const path = join(outDir, 'sfx', `${effect.id}.ogg`)
  let extra = 0
  let result
  // The codec moves the level a little: measure what comes out and correct once or twice.
  for (let attempt = 0; attempt < 3; attempt++) {
    const finished = finishEffect(effect.make(), extra)
    const channels = finished.mono ? [finished.l] : [finished.l, finished.r]
    const { bytes, decoded } = encodeVerified(channels, path, finished.mono ? [48, 64, 96, 128] : [64, 96, 128], { title: effect.title, album: 'Doory sound effects' })
    const loudness = activeLoudness(decoded)
    result = { bytes, decoded, channels, loudness }
    const error = SFX_TARGET_LUFS - loudness
    const headroom = SFX_PEAK_CEILING_DB - toDb(samplePeak(decoded)) - 0.3
    if (Math.abs(error) <= 0.7 || headroom <= 0.3) break
    extra += clamp(Math.min(error, headroom), -6, 6)
  }
  const { bytes, decoded, channels, loudness } = result
  return {
    entry: {
      id: effect.id,
      kind: 'sfx',
      title: effect.title,
      category: effect.category,
      tags: effect.tags,
      loop: false,
      channels: channels.length,
      durationMs: Math.round((decoded[0].length / SR) * 1000),
      lufs: round(loudness),
      peakDb: round(toDb(samplePeak(decoded))),
      file: `sfx/${effect.id}.ogg`,
      bytes: bytes.length,
      sha256: sha256(bytes),
      peaks: peaks(decoded, 40),
    },
  }
}

const old = previous()
const entries = new Map(old)
const jobs = [...MUSIC.map((spec) => ({ id: spec.id, run: () => renderMusic(spec) })), ...EFFECTS.map((effect) => ({ id: effect.id, run: () => renderEffect(effect) }))]
const unknown = only ? [...only].filter((id) => !jobs.some((j) => j.id === id)) : []
if (unknown.length) throw new Error(`unknown id(s): ${unknown.join(', ')}`)

const started = Date.now()
for (const job of jobs) {
  if (only && !only.has(job.id)) continue
  const { entry } = job.run()
  entries.set(entry.id, entry)
  console.log(`${entry.kind.padEnd(5)} ${entry.id.padEnd(24)} ${(entry.durationMs / 1000).toFixed(2).padStart(6)} s  ${String(entry.bytes).padStart(7)} B  ${entry.lufs} LUFS  ${entry.peakDb} dBFS`)
}

const ordered = [...MUSIC.map((s) => s.id), ...EFFECTS.map((e) => e.id)].map((id) => entries.get(id)).filter(Boolean)
writeJson(manifestPath, { schema: 1, release: RELEASE, license: LICENSE, tracks: ordered, packs: old.size ? JSON.parse(readFileSync(manifestPath, 'utf8')).packs : [] })
const total = ordered.reduce((sum, t) => sum + t.bytes, 0)
console.log(`${ordered.length} files, ${(total / 1e6).toFixed(2)} MB in ${((Date.now() - started) / 1000).toFixed(0)} s`)
